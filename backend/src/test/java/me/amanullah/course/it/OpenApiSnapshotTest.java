package me.amanullah.course.it;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import org.junit.jupiter.api.Test;
import tools.jackson.core.util.DefaultIndenter;
import tools.jackson.core.util.DefaultPrettyPrinter;
import tools.jackson.core.util.Separators;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.JsonNodeFactory;
import tools.jackson.databind.node.ObjectNode;

/**
 * Guards the public API contract: the OpenAPI document generated by springdoc ({@code /v3/api-docs}) must match the
 * committed snapshot {@code backend/openapi/openapi.json}. CI compares that snapshot with the base branch's one
 * ({@code oasdiff breaking}) and the frontend contract-drift check reads it.
 *
 * <p>After an intentional API change, regenerate the snapshot and commit it:
 *
 * <pre>
 * ./mvnw test -Dtest=OpenApiSnapshotTest -Dopenapi.update=true
 * </pre>
 */
class OpenApiSnapshotTest extends IntegrationTestSupport {

    static final Path SNAPSHOT = Path.of("openapi", "openapi.json");

    private static final JsonMapper JSON = JsonMapper.builder().build();

    @Test
    void generatedApiDocsMatchCommittedSnapshot() throws Exception {
        String body = mvc.perform(get("/v3/api-docs")).andExpect(status().isOk())
                .andReturn().getResponse().getContentAsString(StandardCharsets.UTF_8);
        String generated = normalize(body);

        if (Boolean.getBoolean("openapi.update")) {
            Files.createDirectories(SNAPSHOT.getParent());
            Files.writeString(SNAPSHOT, generated, StandardCharsets.UTF_8);
            return;
        }

        assertThat(SNAPSHOT)
                .as("OpenAPI snapshot %s is missing. Generate it with: "
                        + "./mvnw test -Dtest=OpenApiSnapshotTest -Dopenapi.update=true", SNAPSHOT)
                .exists();
        String committed = Files.readString(SNAPSHOT, StandardCharsets.UTF_8);
        if (!generated.equals(committed)) {
            // Keep the generated document for `diff openapi/openapi.json target/openapi/openapi.generated.json`.
            Path actual = Path.of("target", "openapi", "openapi.generated.json");
            Files.createDirectories(actual.getParent());
            Files.writeString(actual, generated, StandardCharsets.UTF_8);
        }
        assertThat(generated)
                .as("The API contract changed. If intended, regenerate %s with "
                        + "'./mvnw test -Dtest=OpenApiSnapshotTest -Dopenapi.update=true' and commit it "
                        + "(CI checks the change for breaking changes with oasdiff).", SNAPSHOT)
                .isEqualTo(committed);
    }

    /** Sorted keys, without the request-dependent {@code servers} block, pretty-printed with a trailing newline. */
    static String normalize(String json) {
        JsonNode root = JSON.readTree(json);
        if (root instanceof ObjectNode object) {
            object.remove("servers");
        }
        DefaultPrettyPrinter printer = new DefaultPrettyPrinter()
                .withSeparators(Separators.createDefaultInstance()
                        .withObjectNameValueSpacing(Separators.Spacing.AFTER))
                .withObjectIndenter(new DefaultIndenter("  ", "\n"))
                .withArrayIndenter(new DefaultIndenter("  ", "\n"));
        return JSON.writer().with(printer).writeValueAsString(sorted(root)) + "\n";
    }

    private static JsonNode sorted(JsonNode node) {
        JsonNodeFactory nodes = JsonNodeFactory.instance;
        if (node.isObject()) {
            List<String> names = new ArrayList<>(node.propertyNames());
            Collections.sort(names);
            ObjectNode result = nodes.objectNode();
            for (String name : names) {
                result.set(name, sorted(node.get(name)));
            }
            return result;
        }
        if (node.isArray()) {
            ArrayNode result = nodes.arrayNode();
            node.forEach(child -> result.add(sorted(child)));
            return result;
        }
        return node;
    }
}
